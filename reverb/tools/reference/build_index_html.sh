# Converts a manifest.csv (written by generate_reference_samples's own
# --manifest-csv) into a single self-contained index.html: a sortable,
# filterable table with an inline <audio> player for each dry/reference
# pair, so a whole batch_export.sh sweep can be browsed and listened to
# in a browser instead of hunting through folders. Called automatically
# at the end of batch_export.sh; also runnable standalone if you already
# have a manifest.csv and just want to (re)build its index.html.
#
# Usage: ./build_index_html.sh <manifest.csv> <output index.html>
#
# No external dependencies (no CDN scripts/styles, matching this
# project's own dependency-free tooling convention) -- everything is
# inline in the one generated HTML file, which only ever needs to be
# opened next to the run_dir subdirectories manifest.csv itself
# references (relative paths throughout).

set -euo pipefail

if [ $# -ne 2 ]; then
    echo "usage: $0 <manifest.csv> <output index.html>" >&2
    exit 1
fi
MANIFEST="$1"
OUT_HTML="$2"

if [ ! -f "$MANIFEST" ]; then
    echo "ERROR: $MANIFEST not found" >&2
    exit 1
fi

{
cat <<'HTML_HEAD'
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Reverb reference export</title>
<style>
  :root { color-scheme: dark; }
  body { font-family: -apple-system, Segoe UI, Helvetica, Arial, sans-serif; background: #14161a; color: #e8e8e8; margin: 0; padding: 20px; }
  h1 { font-size: 18px; font-weight: 600; margin: 0 0 4px; }
  .sub { color: #9aa0a8; font-size: 13px; margin-bottom: 16px; }
  #filter { width: 100%; max-width: 420px; padding: 8px 10px; border-radius: 6px; border: 1px solid #3a3f46; background: #1d2025; color: #e8e8e8; font-size: 14px; margin-bottom: 14px; }
  table { border-collapse: collapse; width: 100%; font-size: 13px; }
  th, td { padding: 6px 10px; border-bottom: 1px solid #2a2e34; text-align: left; white-space: nowrap; }
  th { position: sticky; top: 0; background: #1d2025; cursor: pointer; user-select: none; }
  th:hover { color: #fff; }
  th.sorted-asc::after { content: " \25B2"; }
  th.sorted-desc::after { content: " \25BC"; }
  tr:hover td { background: #1a1d22; }
  audio { height: 28px; width: 220px; }
  .count { color: #9aa0a8; font-size: 12px; margin: 8px 0; }
  .rundir { color: #9aa0a8; font-size: 11px; }
</style>
</head>
<body>
<h1>Reverb reference export</h1>
<div class="sub">Generated by tools/reference/batch_export.sh + build_index_html.sh -- click a column header to sort, type below to filter.</div>
<input id="filter" type="text" placeholder="Filter (matches any column)...">
<div class="count" id="count"></div>
<table id="tbl">
<thead><tr>
  <th data-key="run_dir">Run</th>
  <th data-key="signal_name">Signal</th>
  <th data-key="length_m">Length (m)</th>
  <th data-key="width_m">Width (m)</th>
  <th data-key="height_m">Height (m)</th>
  <th data-key="absorption">Absorption</th>
  <th data-key="target_t60_s">T60 (s)</th>
  <th data-key="order">Order</th>
  <th data-key="sample_rate">Sample Rate</th>
  <th>Dry</th>
  <th>Reference</th>
</tr></thead>
<tbody id="tbody"></tbody>
</table>
<script>
const rows =
HTML_HEAD

awk 'BEGIN{FS=","; print "["}
NR==1 { for (i=1;i<=NF;i++) header[i]=$i; next }
{
  if (n>0) print ","
  printf "{"
  for (i=1;i<=NF;i++) {
    key=header[i]; val=$i
    isNum = (key=="length_m" || key=="width_m" || key=="height_m" || key=="absorption" || key=="target_t60_s" || key=="order" || key=="sample_rate")
    if (isNum) {
      if (val=="") printf "\"%s\":null", key
      else printf "\"%s\":%s", key, val
    } else {
      gsub(/"/,"\\\"",val)
      printf "\"%s\":\"%s\"", key, val
    }
    if (i<NF) printf ","
  }
  printf "}"
  n++
}
END{ print "\n]" }' "$MANIFEST"

cat <<'HTML_TAIL'
;

const tbody = document.getElementById('tbody');
const countEl = document.getElementById('count');
let sortKey = null, sortDir = 1;

function fmt(v) { return v === null || v === undefined ? '' : v; }

function render(data) {
  tbody.innerHTML = '';
  for (const r of data) {
    const tr = document.createElement('tr');
    const dryPath = r.run_dir + '/' + r.dry_file;
    const refPath = r.run_dir + '/' + r.reference_file;
    tr.innerHTML =
      '<td class="rundir">' + r.run_dir + '</td>' +
      '<td>' + r.signal_name + '</td>' +
      '<td>' + fmt(r.length_m) + '</td>' +
      '<td>' + fmt(r.width_m) + '</td>' +
      '<td>' + fmt(r.height_m) + '</td>' +
      '<td>' + fmt(r.absorption) + '</td>' +
      '<td>' + fmt(r.target_t60_s) + '</td>' +
      '<td>' + fmt(r.order) + '</td>' +
      '<td>' + fmt(r.sample_rate) + '</td>' +
      '<td><audio controls preload="none" src="' + dryPath + '"></audio></td>' +
      '<td><audio controls preload="none" src="' + refPath + '"></audio></td>';
    tbody.appendChild(tr);
  }
  countEl.textContent = data.length + ' file' + (data.length === 1 ? '' : 's');
}

function applyFilterAndSort() {
  const q = document.getElementById('filter').value.toLowerCase();
  let data = rows.filter(r => !q || Object.values(r).some(v => String(fmt(v)).toLowerCase().includes(q)));
  if (sortKey) {
    data = data.slice().sort((a, b) => {
      const av = a[sortKey], bv = b[sortKey];
      if (av === null) return 1;
      if (bv === null) return -1;
      if (typeof av === 'number' && typeof bv === 'number') return (av - bv) * sortDir;
      return String(av).localeCompare(String(bv)) * sortDir;
    });
  }
  render(data);
}

document.getElementById('filter').addEventListener('input', applyFilterAndSort);

for (const th of document.querySelectorAll('th[data-key]')) {
  th.addEventListener('click', () => {
    const key = th.dataset.key;
    if (sortKey === key) sortDir *= -1; else { sortKey = key; sortDir = 1; }
    for (const other of document.querySelectorAll('th')) other.classList.remove('sorted-asc', 'sorted-desc');
    th.classList.add(sortDir === 1 ? 'sorted-asc' : 'sorted-desc');
    applyFilterAndSort();
  });
}

applyFilterAndSort();
</script>
</body>
</html>
HTML_TAIL
} > "$OUT_HTML"

echo "Wrote $OUT_HTML ($(grep -c '^' "$MANIFEST") manifest lines)"
